"""Convert discovered TradingView indicators and publish them to the chart.

This is the second half of the TradingView pipeline. The first half turns
*strategies* into Strategy API V2 sources and keeps only the ones a backtest
endorses. An indicator has no backtest to offer: its whole output is the picture
it draws. So the gate here is different — the converted module must run in the
real indicator sandbox and produce at least one non-empty plot or signal. A
conversion that merely compiles is worth nothing: the earlier implementation
compiled every script and collected no data at all, because the per-bar
statements were nested one level too deep inside a translated function and never
executed.

Published rows use ``asset_type='indicator'``, which is what the indicator IDE
and the chart's indicator picker read. Strategy conversions use
``script_template`` and never appear there, which is why the chart dropdown had
only the three official samples in it.
"""

from __future__ import annotations

import hashlib
import json
import os
import time
from typing import Any, Dict, List, Optional, Sequence

from app.utils.logger import get_logger

logger = get_logger(__name__)

# Bumped whenever the indicator emitter changes the code it generates. Rows
# generated by an older version are regenerated; rows that are merely re-assessed
# are not.
INDICATOR_TRANSPILER_VERSION = max(
    1, int(os.getenv("TRADINGVIEW_INDICATOR_TRANSPILER_VERSION", "1"))
)

# How many scripts one pass may convert. Translation is roughly a second per
# script and the sandbox is a subprocess each, so this is a wall-clock lever, not
# a correctness one.
DEFAULT_CONVERT_BATCH = max(1, int(os.getenv("TRADINGVIEW_INDICATOR_BATCH", "40")))

# An indicator is only worth publishing if it actually draws. A plot whose data
# is entirely ``None`` renders as an empty pane, which a reader cannot tell
# apart from a failed conversion.
MIN_DRAWN_POINTS = max(1, int(os.getenv("TRADINGVIEW_INDICATOR_MIN_POINTS", "10")))

# The chart sandbox budget. It is the production value, deliberately not raised
# here: publishing something the IDE cannot open would be a false endorsement.
SANDBOX_TIMEOUT_SEC = max(5, int(os.getenv("TRADINGVIEW_INDICATOR_TIMEOUT_SEC", "20")))

__all__ = [
    "INDICATOR_TRANSPILER_VERSION",
    "convert_pending_indicators",
    "indicator_status",
]


_INSERT_SQL = """
INSERT INTO qd_tv_indicators
    (script_id_part, transpiler_version, status, plots, signals, warnings,
     diagnostics, code_hash, created_at, updated_at)
VALUES (?, ?, ?, ?, ?, ?::jsonb, ?::jsonb, ?, NOW(), NOW())
ON CONFLICT (script_id_part) DO UPDATE
   SET transpiler_version = EXCLUDED.transpiler_version,
       status = EXCLUDED.status,
       plots = EXCLUDED.plots,
       signals = EXCLUDED.signals,
       warnings = EXCLUDED.warnings,
       diagnostics = EXCLUDED.diagnostics,
       code_hash = EXCLUDED.code_hash,
       -- A published listing survives a regeneration only while the generated
       -- code is byte-identical. Anything else means the previous run no longer
       -- describes what is on the chart.
       indicator_id = CASE
           WHEN qd_tv_indicators.indicator_id IS NOT NULL
            AND qd_tv_indicators.code_hash = EXCLUDED.code_hash
           THEN qd_tv_indicators.indicator_id
           ELSE NULL
       END,
       updated_at = NOW()
"""

_CANDIDATE_SQL = """
SELECT s.script_id_part, s.name, s.source_code
  FROM qd_tv_scripts s
  LEFT JOIN qd_tv_indicators c ON c.script_id_part = s.script_id_part
 WHERE s.tv_script_type = 'indicator'
   AND COALESCE(s.source_code, '') <> ''
   AND s.source_code LIKE '%%plot%%'
   AND s.source_code NOT LIKE '%%polyline.%%'
   AND (
        c.script_id_part IS NULL
        OR c.transpiler_version <> ?
        OR c.status = 'pending'
   )
 ORDER BY s.likes_count DESC NULLS LAST, s.id ASC
 LIMIT ?
"""


def _code_hash(code: str) -> str:
    return hashlib.sha256((code or "").encode("utf-8")).hexdigest()


def _sample_frame():
    """Return the frame the publishing gate executes against.

    It is the same generator the indicator IDE validates with, so a module that
    passes here is exactly a module that passes when a reader opens it.
    """
    from app.services.indicator_validation import generate_mock_df

    return generate_mock_df()


def _drawn_points(output: Dict[str, Any]) -> tuple[int, int]:
    """Count how many plot values and markers actually carry data."""
    points = 0
    for plot in output.get("plots") or []:
        if not isinstance(plot, dict):
            continue
        for value in plot.get("data") or []:
            if value is not None:
                points += 1
    signals = 0
    for signal in output.get("signals") or []:
        if not isinstance(signal, dict):
            continue
        if any(value is not None and value != 0 for value in signal.get("data") or []):
            signals += 1
    return points, signals


def _run_in_sandbox(code: str) -> Dict[str, Any]:
    """Execute one converted module in the real indicator sandbox."""
    from app.utils.safe_exec import safe_exec_indicator_isolated

    return safe_exec_indicator_isolated(
        code,
        _sample_frame(),
        {},
        timeout=SANDBOX_TIMEOUT_SEC,
    )


def _record(
    script_id_part: str,
    *,
    status: str,
    version: int,
    plots: int = 0,
    signals: int = 0,
    warnings: Optional[List[str]] = None,
    diagnostics: Optional[Dict[str, Any]] = None,
    code_hash: str = "",
) -> None:
    from app.utils.db import get_db_connection

    with get_db_connection() as db:
        cur = db.cursor()
        try:
            cur.execute(
                _INSERT_SQL,
                (
                    script_id_part,
                    version,
                    status,
                    plots,
                    signals,
                    json.dumps(list(warnings or [])),
                    json.dumps(diagnostics or {}, default=str),
                    code_hash,
                ),
            )
            db.commit()
        finally:
            cur.close()


def _publish(
    *,
    user_id: int,
    name: str,
    code: str,
    description: str,
    script_id_part: str,
) -> int:
    """Insert or update the marketplace row this indicator hangs on."""
    from app.utils.db import get_db_connection

    with get_db_connection() as db:
        cur = db.cursor()
        try:
            # ``source_script_source_id`` is the strategy-side identity and stays
            # NULL here; an indicator is identified by the TradingView script it
            # came from, which no other table stores.
            cur.execute(
                """
                SELECT id FROM qd_indicator_codes
                 WHERE user_id = ?
                   AND COALESCE(asset_type, 'indicator') = 'indicator'
                   AND name = ?
                 ORDER BY id ASC
                 LIMIT 1
                """,
                (int(user_id), name),
            )
            row = cur.fetchone()
            if row:
                indicator_id = int(row["id"] if isinstance(row, dict) else row[0])
                cur.execute(
                    """
                    UPDATE qd_indicator_codes
                       SET code = ?, description = ?, publish_to_community = 1,
                           pricing_type = 'free', price = 0, is_encrypted = 0,
                           vip_free = FALSE, asset_type = 'indicator',
                           review_status = 'approved', review_note = '',
                           source_language = 'pine',
                           updatetime = ?, updated_at = NOW()
                     WHERE id = ? AND user_id = ?
                    """,
                    (code, description, int(time.time()), indicator_id, int(user_id)),
                )
                db.commit()
                return indicator_id

            cur.execute(
                """
                INSERT INTO qd_indicator_codes
                  (user_id, is_buy, end_time, name, code, description,
                   publish_to_community, pricing_type, price, is_encrypted,
                   vip_free, asset_type, review_status, source_language,
                   createtime, updatetime, created_at, updated_at)
                VALUES (?, 0, 1, ?, ?, ?, 1, 'free', 0, 0, FALSE, 'indicator',
                        'approved', 'pine', ?, ?, NOW(), NOW())
                """,
                (
                    int(user_id),
                    name,
                    code,
                    description,
                    int(time.time()),
                    int(time.time()),
                ),
            )
            indicator_id = int(cur.lastrowid or 0)
            db.commit()
            return indicator_id
        finally:
            cur.close()


def _display_name(raw: str) -> str:
    """Return the marketplace title for a converted indicator."""
    title = " ".join(str(raw or "").split()).strip()
    if not title:
        return "[TV] Indicator"
    if title.startswith("[TV]"):
        return title
    return f"[TV] {title}"


def convert_pending_indicators(
    *,
    limit: int = DEFAULT_CONVERT_BATCH,
    user_id: int = 1,
    publish: bool = True,
) -> Dict[str, Any]:
    """Convert, sandbox-check and optionally publish pending TV indicators.

    ``publish`` is separate from conversion on purpose: a dry run should be able
    to answer "how many of these would I ship" without touching the marketplace.
    """
    from app.services.pine_transpiler.chart import transpile_indicator

    summary: Dict[str, Any] = {
        "requested": int(limit),
        "candidates": 0,
        "transpiled": 0,
        "drawn": 0,
        "published": 0,
        "failed": 0,
        "skipped": 0,
        "results": [],
    }
    if limit <= 0:
        return summary

    from app.utils.db import get_db_connection

    with get_db_connection() as db:
        cur = db.cursor()
        try:
            cur.execute(
                _CANDIDATE_SQL,
                (INDICATOR_TRANSPILER_VERSION, int(limit)),
            )
            rows = list(cur.fetchall() or [])
        finally:
            cur.close()

    summary["candidates"] = len(rows)
    for row in rows:
        script_id_part = str(row["script_id_part"])
        raw_name = str(row["name"] or "")
        source = str(row["source_code"] or "")
        result = transpile_indicator(source, name=raw_name)
        if not result.ok or not result.code:
            summary["failed"] += 1
            summary["results"].append(
                {"script_id_part": script_id_part, "status": "transpile_failed",
                 "error": str(result.error or result.blockers)}
            )
            _record(
                script_id_part,
                status="transpile_failed",
                version=INDICATOR_TRANSPILER_VERSION,
                warnings=list(result.warnings or []),
                diagnostics={"error": str(result.error or ""),
                             "blockers": list(result.blockers or [])},
            )
            continue
        summary["transpiled"] += 1
        code_hash = _code_hash(result.code)

        outcome = _run_in_sandbox(result.code)
        if not outcome.get("success"):
            summary["failed"] += 1
            error = str(outcome.get("error") or "")[:2000]
            summary["results"].append(
                {"script_id_part": script_id_part, "status": "sandbox_failed", "error": error}
            )
            _record(
                script_id_part,
                status="sandbox_failed",
                version=INDICATOR_TRANSPILER_VERSION,
                warnings=list(result.warnings or []),
                diagnostics={"error": error},
                code_hash=code_hash,
            )
            continue

        output = (outcome.get("result") or {}).get("output") or {}
        points, signals = _drawn_points(output)
        if points < MIN_DRAWN_POINTS and signals == 0:
            # The module runs but the pane would be blank: every plot is a NaN
            # tail because the script's own condition never held on this frame.
            summary["skipped"] += 1
            summary["results"].append(
                {"script_id_part": script_id_part, "status": "blank",
                 "points": points, "signals": signals}
            )
            _record(
                script_id_part,
                status="blank",
                version=INDICATOR_TRANSPILER_VERSION,
                plots=len(output.get("plots") or []),
                warnings=list(result.warnings or []),
                diagnostics={"drawn_points": points, "signals": signals},
                code_hash=code_hash,
            )
            continue

        summary["drawn"] += 1
        plots = list(output.get("plots") or [])
        indicator_id = 0
        if publish:
            label = _display_name(raw_name)
            description = (
                f"Converted from a public TradingView indicator"
                f" ({script_id_part}). Draws {len(plots)} series"
                f" and {len(output.get('signals') or [])} markers."
            )
            try:
                indicator_id = _publish(
                    user_id=user_id,
                    name=label,
                    code=result.code,
                    description=description,
                    script_id_part=script_id_part,
                )
                summary["published"] += 1
            except Exception as exc:  # pragma: no cover - defensive
                logger.error("publishing indicator %s failed: %s", script_id_part, exc)
        _record(
            script_id_part,
            status="published" if indicator_id else "ready",
            version=INDICATOR_TRANSPILER_VERSION,
            plots=len(plots),
            signals=len(output.get("signals") or []),
            warnings=list(result.warnings or []),
            diagnostics={"drawn_points": points, "indicator_id": indicator_id},
            code_hash=code_hash,
        )
        summary["results"].append(
            {"script_id_part": script_id_part, "status": "published" if indicator_id else "ready",
             "indicator_id": indicator_id, "plots": len(plots)}
        )
    return summary


def indicator_status() -> Dict[str, Any]:
    """Return conversion and publishing counts for the indicator corpus."""
    from app.utils.db import get_db_connection

    with get_db_connection() as db:
        cur = db.cursor()
        try:
            cur.execute(
                """
                SELECT status, COUNT(*) AS total
                  FROM qd_tv_indicators
                 GROUP BY status
                """
            )
            conversions = {
                str(row["status"]): int(row["total"]) for row in (cur.fetchall() or [])
            }
            cur.execute(
                """
                SELECT COUNT(*) AS total FROM qd_indicator_codes
                 WHERE publish_to_community = 1
                   AND COALESCE(asset_type, 'indicator') = 'indicator'
                """
            )
            row = cur.fetchone()
            listed = int(row["total"]) if row else 0
        finally:
            cur.close()
    return {
        "transpiler_version": INDICATOR_TRANSPILER_VERSION,
        "conversions": conversions,
        "listed": listed,
    }
