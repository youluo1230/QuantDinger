def _candidate_rows(limit: int, *, min_score: int) -> List[Dict[str, Any]]:
    if limit <= 0:
        return []
    with get_db_connection() as db:
        cur = db.cursor()
        try:
            # Skip rows already converted (or already failed for this version).
            cur.execute(
                """
                SELECT s.id, s.script_id_part, s.name, s.author, s.source_code,
                       s.chart_interval, s.symbol_name, s.migratability_score,
                       s.likes_count
                  FROM qd_tv_scripts s
                  LEFT JOIN qd_tv_conversions c ON c.script_id_part = s.script_id_part
                 WHERE s.source_fetched_at IS NOT NULL
                   AND s.source_code <> ''
                   AND s.migratability_score >= ?
                   AND (c.id IS NULL
                        OR c.status IN ('pending', 'transpile_failed', 'compile_failed')
                        OR c.transpiler_version <> ?)
                 ORDER BY s.migratability_score DESC, s.likes_count DESC, s.id ASC
                 LIMIT ?
                """,
                (min_score, TRANSPILER_VERSION, limit),
            )
            return [dict(row) for row in (cur.fetchall() or [])]
        finally:
            cur.close()


def _source_name(row: Dict[str, Any]) -> str:
    name = str(row.get("name") or "").strip() or "TradingView strategy"
    author = str(row.get("author") or "").strip()
    # Keep the TradingView attribution visible in the library list; the
    # marketplace licence note also requires it.
    prefix = "[TV]"
    return f"{prefix} {name}"[:250] + (f" (by {author})" if author else "")


def _source_description(row: Dict[str, Any], assessment: Dict[str, Any]) -> str:
    parts = [
        f"Ported from TradingView strategy {row.get('script_id_part')}.",
        f"Original author: {row.get('author') or 'unknown'}.",
        f"Migratability score: {int(assessment.get('score') or 0)}/100.",
    ]
    # Record what the strategy was actually measured on, so a listing cannot be
    # mistaken for the instrument it was written for when the venue has no data
    # source here and the configured default was substituted.
    upstream = str(row.get("symbol_name") or "").strip()
    market, instrument = _instrument_for_symbol(upstream)
    if upstream:
        if market and instrument:
            parts.append(f"Published on {upstream}, evaluated on {market}:{instrument}.")
        else:
            parts.append(
                f"Published on {upstream}, evaluated on {_DEFAULT_INSTRUMENT} "
                f"because that venue has no data source here."
            )
    warnings = assessment.get("stats", {}).get("unsupported_calls") or []
    if warnings:
        shown = ", ".join(str(item) for item in list(warnings)[:8])
        parts.append(f"Dropped TradingView-only calls: {shown}.")
    return " ".join(parts)


def convert_pending_scripts(
    *,
    limit: int = 8,
    user_id: int = 1,
    min_score: int = DEFAULT_MIN_SCORE,
) -> Dict[str, Any]:
    """Transpile candidates into private Strategy V2 sources.

    Compilation is the gate: ``compile_strategy_v2`` must accept the generated
    code before a ``qd_script_sources`` row is created.
    """
    from app.services.script_source import get_script_source_service
    from app.services.strategy_v2 import compile_strategy_v2, strategy_source_code_hash

    rows = _candidate_rows(limit, min_score=min_score)
    transpiled = 0
    compiled = 0
    created = 0
    failures: List[Dict[str, str]] = []
    module = None

    for row in rows:
        script_id_part = str(row.get("script_id_part") or "")
        source = str(row.get("source_code") or "")
        if not script_id_part or not source:
            continue
        # Translate onto the timeframe and instrument upstream actually published.
        # Measuring a 15-minute scalper on hourly bars, or an S&P strategy on
        # Bitcoin, evaluates a strategy the author never wrote.
        frequency = _frequency_for_interval(row.get("chart_interval"))
        market, instrument = _instrument_for_symbol(row.get("symbol_name"))
        symbol = _resolved_instrument(market, instrument)
        try:
            module = module or _assess_module()
            result = module.transpile_pine(
                source,
                symbol=symbol,
                timeframe=frequency,
                name=str(row.get("name") or ""),
            )
        except Exception as exc:
            logger.exception("Transpile raised for %s", script_id_part)
            _record_conversion(
                script_id_part=script_id_part,
                source_id=None,
                status="transpile_failed",
                blockers=[],
                warnings=[],
                diagnostics={"error": str(exc)},
                code_hash="",
            )
            failures.append({"script_id_part": script_id_part, "stage": "transpile", "error": str(exc)})
            continue

        blockers = list(getattr(result, "blockers", []) or [])
        warnings = list(getattr(result, "warnings", []) or [])
        code = getattr(result, "code", None)
        ok = bool(getattr(result, "ok", False)) and bool(code)
        stats = dict(getattr(result, "stats", {}) or {})

        if not ok:
            _record_conversion(
                script_id_part=script_id_part,
                source_id=None,
                status="transpile_failed",
                blockers=blockers,
                warnings=warnings,
                diagnostics={"stats": stats, "error": getattr(result, "error", None)},
                code_hash="",
            )
            failures.append(
                {
                    "script_id_part": script_id_part,
                    "stage": "transpile",
                    "error": getattr(result, "error", None) or ",".join(blockers) or "not convertible",
                }
            )
            continue
        transpiled += 1

        # The transpiler is not the authority on compilability; the strategy
        # contract is. A candidate that fails here must not enter the library.
        try:
            compile_strategy_v2(code)
        except Exception as exc:
            code_value = getattr(exc, "code", "") or ""
            _record_conversion(
                script_id_part=script_id_part,
                source_id=None,
                status="compile_failed",
                blockers=blockers,
                warnings=warnings,
                diagnostics={"stats": stats, "compile_error": str(exc), "compile_code": code_value},
                code_hash=strategy_source_code_hash(code),
            )
            failures.append(
                {
                    "script_id_part": script_id_part,
                    "stage": "compile",
                    "error": f"{code_value}: {exc}".strip(": "),
                }
            )
            continue
        compiled += 1

        # Re-converting the same script must update the existing source instead
        # of littering the library with duplicates.
        existing_source_id = _existing_source_id(script_id_part)
        service = get_script_source_service()
        params = dict(getattr(result, "params", {}) or {})
        try:
            if existing_source_id:
                service.update_source(
                    existing_source_id,
                    user_id,
                    {
                        "name": _source_name(row),
                        "description": _source_description(row, {"score": row.get("migratability_score"), "stats": stats}),
                        "code": code,
                        "param_schema": params,
                        "metadata": {
                            "tradingview": {
                                "script_id_part": script_id_part,
                                "author": row.get("author") or "",
                                "likes_count": int(row.get("likes_count") or 0),
                                "source_chars": len(source),
                            }
                        },
                    },
                )
                source_id = existing_source_id
            else:
                source_id = service.create_source(
                    {
                        "user_id": user_id,
                        "name": _source_name(row),
                        "description": _source_description(
                            row, {"score": row.get("migratability_score"), "stats": stats}
                        ),
                        "code": code,
                        "asset_type": "script",
                        "param_schema": params,
                        "visibility": "private",
                        "status": "draft",
                        "metadata": {
                            "tradingview": {
                                "script_id_part": script_id_part,
                                "author": row.get("author") or "",
                                "likes_count": int(row.get("likes_count") or 0),
                                "source_chars": len(source),
                            }
                        },
                    }
                )
                created += 1
        except Exception as exc:
            logger.exception("Could not persist converted source for %s", script_id_part)
            _record_conversion(
                script_id_part=script_id_part,
                source_id=existing_source_id or None,
                status="persist_failed",
                blockers=blockers,
                warnings=warnings,
                diagnostics={"stats": stats, "error": str(exc)},
                code_hash=strategy_source_code_hash(code),
            )
            failures.append({"script_id_part": script_id_part, "stage": "persist", "error": str(exc)})
            continue

        _record_conversion(
            script_id_part=script_id_part,
            source_id=source_id,
            status="ready",
            blockers=blockers,
            warnings=warnings,
            diagnostics={"stats": stats},
            code_hash=strategy_source_code_hash(code),
        )

    summary = {
        "requested": limit,
        "candidates": len(rows),
        "transpiled": transpiled,
        "compiled": compiled,
        "created": created,
        "updated": compiled - created,
        "failures": failures[:20],
    }
    logger.info("TradingView conversion batch finished: %s", summary)
    return summary


#: ``context.subscribe(frequency="...")`` as emitted by the transpiler.
_SUBSCRIBE_PATTERN = re.compile(r"""context\.subscribe\(\s*frequency\s*=\s*["']([^"']+)["']""")

#: Frequencies a strategy declares. Read from the generated source rather than
#: from ``compile_strategy_v2`` because this runs inside a loop over candidates
#: and a full compile per candidate is far more expensive than a regex.
def _interval_minutes(raw: str) -> int:
    """Read a TradingView interval token as a duration in minutes, or 0.

    Handles the shapes the feed actually uses: a bare minute count (``240``),
    and a count with a unit (``60m``, ``4h``, ``1D``, ``1W``). A capital ``M``
    is a month upstream and is rejected here, since months are outside the
    runtime's subscription grid.
    """
    text = str(raw or "").strip()
    if not text:
        return 0
    if text.isdigit():
        return int(text)
    match = re.fullmatch(r"(\d+)\s*([mhdwMDW])", text)
    if not match:
        return 0
    amount, unit = int(match.group(1)), match.group(2)
    if unit == "M":
        return 0  # monthly: not a subscription frequency
    per_unit = {"m": 1, "h": 60, "d": 1440, "w": 10080}[unit.lower()]
    return amount * per_unit if amount > 0 else 0


def _nearest_grid_frequency(minutes: int) -> str:
    """Snap a duration onto the closest subscribed frequency.

    Ties go to the shorter bar: a strategy written for an in-between duration
    keeps more of its entry granularity on the smaller grid, and the engine
    replays bar by bar, so the shorter bar is the more faithful approximation.
    """
    from app.services.strategy_v2.frequencies import (
        FREQUENCY_SECONDS,
        SUPPORTED_SUBSCRIPTION_FREQUENCIES,
    )

    if minutes <= 0:
        return _DEFAULT_FREQUENCY
    best = min(
        SUPPORTED_SUBSCRIPTION_FREQUENCIES,
        key=lambda item: (abs(FREQUENCY_SECONDS[item] / 60.0 - minutes), FREQUENCY_SECONDS[item]),
    )
    return best


def _driving_frequency(code: str) -> Tuple[str, List[str]]:
    """Return the frequency the generated strategy actually runs on, plus extras.

    The generated module declares its own subscriptions, and the engine replays
    on the shortest one. Deriving the window from the code instead of from the
    configured default keeps the two in step: a strategy converted onto 15m bars
    must be measured over a 15m window, not an hourly one.
    ``context.subscribe`` order is not meaningful here, so the shortest declared
    frequency wins, matching ``driving_frequency`` in the engine.
    """
    from app.services.strategy_v2.frequencies import frequency_seconds

    declared = _declared_frequencies(code)
    if not declared:
        return _DEFAULT_FREQUENCY, []
    ordered = sorted(declared, key=frequency_seconds)
    return ordered[0], ordered[1:]


def _crypto_pair(body: str) -> str:
    """Reshape a venue ticker into the ``BASE/QUOTE`` pair the runtime loads.

    ``BINANCE:BTCUSDT`` becomes ``BTC/USDT``; ``BTCUSDT.P`` has the perpetual
    suffix stripped first. Concatenated tickers are ambiguous in principle, so
    the quote asset is matched longest-first and a ticker with no recognisable
    quote is left alone.
    """
    text = body.upper()
    for suffix in _SYMBOL_SUFFIXES:
        if text.endswith(suffix.upper()):
            text = text[: -len(suffix)]
            break
    # Some venues publish the perpetual marker in the ticker itself.
    if text.endswith("PERP") and len(text) > 4:
        text = text[:-4]
    if "/" in text:
        return text
    for quote in _CRYPTO_QUOTES:
        if text.endswith(quote) and len(text) > len(quote):
            return f"{text[: -len(quote)]}/{quote}"
    return text


def _fx_pair(body: str) -> str:
    """Reshape a broker FX ticker into ``BASE/QUOTE``.

    ``OANDA:EURUSD`` becomes ``EUR/USD``; metals such as ``XAUUSD`` map through
    a small table because the runtime's forex provider names them explicitly.
    """
    text = body.upper()
    for suffix in _SYMBOL_SUFFIXES:
        if text.endswith(suffix.upper()):
            text = text[: -len(suffix)]
            break
    if "/" in text:
        return text
    if text in _CFD_SYMBOLS:
        return _CFD_SYMBOLS[text]
    for base in _FX_CODES:
        if text.startswith(base) and len(text) > len(base):
            return f"{base}/{text[len(base):]}"
    return text


def _instrument_for_symbol(symbol_name: str) -> Tuple[str, str]:
    """Map an upstream symbol into ``(market, symbol)`` the runtime can load.

    TradingView names the broker or venue a script was written against
    (``BINANCE:BTCUSDT``, ``NASDAQ:AAPL``, ``OANDA:XAUUSD``) while the backtest
    engine only knows markets. Testing every strategy on one fixed instrument
    measured a different strategy than the author wrote: an S&P strategy was
    judged on Bitcoin. This resolves each script onto its own market and ticker.

    Returns ``("", "")`` when the venue has no data source here, so the caller
    can fall back rather than request data that will never arrive.
    """
    raw = str(symbol_name or "").strip()
    if not raw:
        return "", ""
    prefix, _, body = raw.partition(":")
    if not body:
        prefix, body = "", raw
    market = _EXCHANGE_MARKETS.get(prefix.upper())
    if not market:
        return "", ""
    body = body.strip()
    if not body:
        return "", ""

    if market == "Crypto":
        # An index ticker (``INDEX:BTCUSD``) is a spot pair quoted in fiat.
        return market, _crypto_pair(body)
    if market == "Forex":
        return market, _fx_pair(body)
    if market in {"USStock", "HKStock"}:
        text = body.upper()
        for suffix in _SYMBOL_SUFFIXES:
            if text.endswith(suffix.upper()):
                text = text[: -len(suffix)]
                break
        # Exchange indices map onto the provider's index ticker; the rest are
        # plain equity symbols. Indian single stocks are mapped but have no
        # data source here, so they resolve and then report no data rather than
        # being silently substituted with something else.
        return market, _INDEX_SYMBOLS.get(text, text)
    # Futures contracts reference a continuous series; the runtime resolves the
    # root ticker. Vendor symbols and month codes carry no data here.
    text = body.upper()
    for suffix in _SYMBOL_SUFFIXES:
        if text.endswith(suffix.upper()):
            text = text[: -len(suffix)]
            break
    text = re.sub(r"[FGHJKMNQUVXZ]\d{1,2}$", "", text) or text
    return market, _FUTURES_SYMBOLS.get(text, text)


def _resolved_instrument(market: str, instrument: str) -> str:
    """Return the symbol to embed in generated code.

    The market prefix is kept so the engine cannot misinfer the market from the
    ticker: ``EUR/USD`` alone infers as crypto, while ``Forex:EUR/USD`` does not.
    Falls back to the configured instrument when upstream names a venue with no
    data source here.
    """
    if market and instrument:
        return f"{market}:{instrument}"
    return _DEFAULT_INSTRUMENT


def _code_instrument(code: str) -> Tuple[str, str]:
    """Read the market and symbol a generated strategy was translated onto.

    The window limits are per market (a US equity intraday request carries a
    much narrower cap than crypto), so validating against the wrong market
    accepts windows the engine then rejects.
    """
    match = re.search(r'^_SYMBOL\s*=\s*"([^"]*)"', str(code or ""), re.MULTILINE)
    raw = match.group(1) if match else ""
    if not raw:
        return "", ""
    market, _, instrument = raw.partition(":")
    if not instrument:
        return "", raw
    return market, instrument


def _frequency_for_interval(chart_interval: str) -> str:
    """Resolve the timeframe a harvested strategy was published for.

    TradingView reports the interval the author used, which is the only upstream
    evidence about the timeframe the strategy was designed for. Preferring it
    over the configured default matters: judging a 15-minute scalper on hourly
    bars measures a different strategy.

    Intervals the runtime cannot subscribe to (45 minutes, 2 days, 9 minutes)
    legitimately fall back to the default, because ``context.subscribe`` only
    accepts the fixed grid. The fallback is deliberately silent here and visible
    in ``diagnostics`` at conversion time instead.
    """
    raw = str(chart_interval or "").strip()
    if not raw:
        return _DEFAULT_FREQUENCY
    # Capitalised unit tokens are matched before any case folding: ``1M`` means
    # one month upstream, and lowercasing it first would read as one minute.
    if raw.upper() == "M" or raw.upper() == "1M":
        return _DEFAULT_FREQUENCY
    mapped = _INTERVAL_FREQUENCIES.get(raw) or _INTERVAL_FREQUENCIES.get(raw.upper())
    if mapped:
        return mapped
    mapped = _INTERVAL_FREQUENCIES.get(raw.lower())
    if mapped:
        return mapped
    # Anything else that still expresses a duration is snapped to the nearest
    # grid point instead of the default: an 8-hour strategy measured on 4-hour
    # bars is off by 2x, while measuring it on the 1h default would be off by
    # 8x. Tokens with no duration at all (``nonsense``) still fall back.
    minutes = _interval_minutes(raw)
    if minutes:
        return _nearest_grid_frequency(minutes)
    return _DEFAULT_FREQUENCY


def _declared_frequencies(code: str) -> List[str]:
    return [item for item in dict.fromkeys(_SUBSCRIBE_PATTERN.findall(code or "")) if item]


#: Errors that mean "the window is too wide for the data on hand" rather than
#: "the strategy is broken". They are worth retrying on a shorter window:
#: providers keep less history than ``backtest_limits`` permits, and the engine
#: reports the shortfall instead of clipping to what it has.
_WINDOW_TOO_WIDE_MARKERS = (
    "no_market_data",
    "noMarketData",
    "insufficientWarmupData",
    "backtestRangeLimit",
)

#: Windows to fall back to, in days, when the preferred one is unavailable.
_RETRY_WINDOWS = (90, 60, 45, 30, 21, 14, 10, 7, 3)


def _window_too_wide(exc: BaseException) -> bool:
    """True when retrying on a shorter window could succeed."""
    text = str(exc)
    return any(marker in text for marker in _WINDOW_TOO_WIDE_MARKERS)


def _backtest_once(
    service: Any,
    *,
    code: str,
    start: datetime,
    end: datetime,
    user_id: int,
    source_id: int,
    name: str,
    initial_capital: float,
) -> Tuple[int, Dict[str, Any]]:
    """Run one backtest under the per-strategy ceiling.

    The ceiling exists because one pathological strategy must not consume the
    whole batch; it raises rather than returning a partial result so the caller
    can tell a timeout from a strategy that simply did not trade.
    """
    with timeout_context(BACKTEST_TIMEOUT_SEC):
        return service.run(
            user_id=user_id,
            code=code,
            start_date=start,
            end_date=end.replace(hour=23, minute=59, second=59),
            initial_capital=float(initial_capital),
            leverage_enabled=False,
            leverage=1.0,
            commission=0.001,
            slippage=0.0,
            params={},
            strategy_id=None,
            source_id=source_id,
            strategy_name=name,
        )


def _run_with_retries(
    service: Any,
    *,
    code: str,
    start: datetime,
    end: datetime,
    user_id: int,
    source_id: int,
    name: str,
    initial_capital: float,
    market: str,
    symbol: str,
    frequency: str,
    extra_frequencies: Sequence[str],
) -> Tuple[int, Dict[str, Any], datetime, datetime]:
    """Backtest, shrinking the window when the data does not reach back far enough.

    ``backtest_limits`` describes what each timeframe may *legally* request, but
    data providers keep less than that. The engine raises ``noMarketData`` or
    ``insufficientWarmupData`` instead of clipping to the history it has, so a
    strategy that would backtest fine over a month was parked as broken when the
    year-long window came back empty. Retrying narrower distinguishes "this data
    source does not go back that far" from "this strategy does not work".

    Only window-shaped failures are retried: a strategy that raises
    ``NameError`` will raise it again on a shorter window, and retrying would
    waste a batch slot.
    """
    last: Optional[BaseException] = None
    span_days = max(1, (end - start).days)
    for days in (span_days, *(item for item in _RETRY_WINDOWS if item < span_days)):
        attempt_end = end
        attempt_start = attempt_end - timedelta(days=days)
        try:
            run_id, result = _backtest_once(
                service,
                code=code,
                start=attempt_start,
                end=attempt_end,
                user_id=user_id,
                source_id=source_id,
                name=name,
                initial_capital=initial_capital,
            )
            return run_id, result, attempt_start, attempt_end
        except Exception as exc:  # noqa: BLE001 - re-raised below when not window-shaped
            if not _window_too_wide(exc):
                raise
            last = exc
            logger.info(
                "Backtest window of %s days unavailable for source %s (%s); retrying shorter",
                days,
                source_id,
                str(exc)[:160],
            )
    # Every window failed the same way; surface the narrowest attempt's error so
    # the diagnostics say what the smallest request still could not satisfy.
    assert last is not None
    raise last


def _backtest_range(
    frequency: str,
    *,
    warmup_bars: int = 0,
    extra_frequencies: Sequence[str] = (),
    market: str = "Crypto",
    symbol: str = "",
) -> tuple[datetime, datetime]:
    """Return a legal backtest window for the configured frequency.

    ``app/services/backtest_limits.py`` rejects windows longer than the
    per-frequency cap, so the window is clamped instead of hard-coded.

    The window is deliberately short by default. The Strategy V2 engine replays
    bar by bar and recomputes every ``ta.*`` call against the whole visible
    history on each bar, so a multi-year window costs roughly the square of a
    one-year window. A converted TradingView strategy proves nothing extra with
    a longer window than it does with a shorter one, but it can easily take
    minutes instead of seconds, which is the difference between a nightly job
    that drains its queue and one that never finishes.

    ``warmup_bars`` must be supplied because the engine validates the window
    including the warmup it will fetch ahead of the first bar. Checking without
    it accepted windows that the engine then rejected as ``backtestRangeLimit``.

    ``extra_frequencies`` covers strategies that subscribe to more than one
    timeframe. Each subscription carries its own cap — ``1m`` is limited to a
    month while ``1h`` allows years — and the engine rejects the request if any
    subscription exceeds its cap, so the window has to be legal for all of them.
    """
    from app.services.backtest_limits import validate_backtest_range

    end = datetime.now(tz=timezone.utc).replace(tzinfo=None, minute=0, second=0, microsecond=0)
    preferred = max(7, int(os.getenv("TRADINGVIEW_BACKTEST_DAYS", "180")))
    # Never exceed the shortest legal cap for the frequency, and fall back to
    # narrower windows if the configured one is rejected.
    ladder = (365, 180, 90, 60, 45, 30, 21, 14, 10, 7)
    candidates = [preferred] + [days for days in ladder if days < preferred]
    from app.services.backtest_limits import backtest_warmup_calendar_days

    timeframes = [frequency, *(item for item in extra_frequencies if item)]
    # The engine fetches the warmup *before* the window and validates that wider
    # range, so the window has to be shrunk by the same amount here. Ignoring it
    # produced windows that passed this check and still failed inside the engine.
    warmup_days = backtest_warmup_calendar_days(frequency, warmup_bars)
    for days in candidates:
        start = end - timedelta(days=days)
        fetch_start = start - timedelta(days=warmup_days)
        errors = [
            validate_backtest_range(
                market=market,
                symbol=symbol or _DEFAULT_INSTRUMENT,
                timeframe=timeframe,
                start_date=start,
                end_date=end,
                warmup_bars=warmup_bars,
                fetch_start=fetch_start,
            )
            for timeframe in dict.fromkeys(timeframes)
        ]
        if not any(errors):
            return start, end
    return end - timedelta(days=30), end


def backtest_and_publish(
    *,
    limit: int = 5,
    user_id: int = 1,
    min_score: int = DEFAULT_MIN_SCORE,
    initial_capital: float = 10000.0,
    publish: bool = True,
    source_ids: Optional[Sequence[int]] = None,
) -> Dict[str, Any]:
    """Backtest converted sources and publish the ones that clear the gate.

    Publishing reuses the same path as a manual marketplace publish
    (``publish_script_template_from_strategy``), including the
    ``BACKTEST_REQUIRED`` precondition, so the automated and manual flows cannot
    diverge.

    ``source_ids`` restricts the pass to a caller-chosen set of sources. A
    backtest replays the whole window bar by bar and costs tens of seconds per
    strategy, so the only practical way to fill a large corpus is to shard it
    across processes; each shard must be disjoint because two workers racing the
    same conversion row would backtest it twice and publish it twice.
    """
    from app.services.community_service import get_community_service
    from app.services.strategy_v2 import (
        StrategyV2BacktestService,
        strategy_source_code_hash,
    )
    with get_db_connection() as db:
        cur = db.cursor()
        try:
            # ``backtested`` rows already hold a successful run, so a publish
            # pass must pick them up: re-running the backtest would waste minutes
            # and still never publish anything when only fresh rows are selected.
            wanted = ("ready", "backtested") if publish else ("ready",)
            cur.execute(
                """
                SELECT c.script_id_part, c.source_id, c.status, c.backtest_run_id,
                       s.name, s.description, s.code
                  FROM qd_tv_conversions c
                  JOIN qd_script_sources s ON s.id = c.source_id
                 WHERE c.status = ANY(?)
                   AND c.source_id IS NOT NULL
                   AND s.user_id = ?
                   AND (?::int[] IS NULL OR c.source_id = ANY(?::int[]))
                 ORDER BY c.updated_at DESC
                 LIMIT ?
                """,
                (
                    list(wanted),
                    user_id,
                    list(source_ids) if source_ids else None,
                    list(source_ids) if source_ids else None,
                    max(1, int(limit)),
                ),
            )
            rows = [dict(row) for row in (cur.fetchall() or [])]
        finally:
            cur.close()

    service = StrategyV2BacktestService()
    # Resolved lazily: a backtest-only run has no business building the
    # marketplace service, and doing so eagerly made ``publish=False`` pay for
    # expensive eager state it never used.
    community = get_community_service() if publish else None
    results: List[Dict[str, Any]] = []
    published = 0

    for row in rows:
        source_id = int(row["source_id"])
        code = str(row.get("code") or "")
        name = str(row.get("name") or "TradingView strategy")
        primary_frequency, extra_frequencies = _driving_frequency(code)
        code_market, code_symbol = _code_instrument(code)
        if publish and str(row.get("status") or "") == "backtested" and row.get("backtest_run_id"):
            # Already has a successful run: reuse it so a publish pass is cheap
            # and idempotent instead of re-backtesting every time.
            run_id = int(row["backtest_run_id"])
            result = _stored_run_result(run_id)
            start, end = None, None
        else:
            # Resolved per strategy: a converted script may subscribe to several
            # timeframes, and each carries its own window cap. The market matters
            # too: a US equity intraday cap is a fraction of the crypto one.
            start, end = _backtest_range(
                primary_frequency,
                warmup_bars=_WARMUP_BARS,
                extra_frequencies=extra_frequencies,
                market=code_market or "Crypto",
                symbol=code_symbol,
            )
            try:
                run_id, result, start, end = _run_with_retries(
                    service,
                    code=code,
                    start=start,
                    end=end,
                    user_id=user_id,
                    source_id=source_id,
                    name=name,
                    initial_capital=initial_capital,
                    market=code_market or "Crypto",
                    symbol=code_symbol,
                    frequency=primary_frequency,
                    extra_frequencies=extra_frequencies,
                )
            except Exception as exc:
                timed_out = isinstance(exc, (TimeoutError, SandboxTimeoutError))
                logger.exception("Backtest failed for source %s", source_id)
                results.append({"source_id": source_id, "script_id_part": row["script_id_part"], "error": str(exc)})
                # Park the row so a broken strategy does not monopolise every future
                # batch. Without this the row stays ``ready`` and the same failures
                # are retried forever, starving strategies that have never run. A
                # timeout is parked separately because re-running it unchanged would
                # burn the same minutes again.
                _set_conversion_status(
                    row["script_id_part"],
                    status="timeout" if timed_out else "backtest_failed",
                    diagnostics={"error": str(exc)[:2000]},
                )
                # A strategy that no longer backtests must not stay advertised on
                # the strength of a run that was made against different code.
                _delist_rejected_templates(
                    user_id,
                    source_id,
                    reason="Backtest no longer succeeds",
                )
                continue

        # ``totalTrades`` counts closed trades only. A strategy that opens a
        # position and holds it to the end of the window never closes one, so
        # judging evidence by that number alone marks a run that did trade as
        # "never traded" and drops the strategy. Positions still open at the end
        # plus realised executions are the honest measure of activity.
        trades = int(result.get("totalTrades") or 0)
        executions = int(result.get("totalExecutions") or 0)
        open_positions = int(result.get("openPositions") or 0)
        activity = trades + open_positions
        summary = {
            "source_id": source_id,
            "script_id_part": row["script_id_part"],
            "frequency": primary_frequency,
            "market": code_market,
            "symbol": code_symbol,
            "run_id": run_id,
            "range": (
                {"start": start.isoformat(), "end": end.isoformat()}
                if start is not None and end is not None
                else None
            ),
            "totalTrades": trades,
            "totalExecutions": executions,
            "openPositions": open_positions,
            "totalReturn": result.get("totalReturn"),
            "sharpeRatio": result.get("sharpeRatio"),
            "maxDrawdown": result.get("maxDrawdown"),
        }

        # A backtest that never opens a position "succeeds" without exercising
        # the translated strategy at all: the entry condition simply never held.
        # Publishing that to the marketplace would advertise an unverified
        # strategy as if it had passed, so require real evidence of trading.
        #
        # Evidence of trading and a sample worth trusting are two different
        # questions and must not share one number. ``totalTrades`` only counts
        # closed trades, so a strategy that buys once and holds to the end of
        # the window reports zero while ``positions`` still holds it; adding the
        # open position back answers the first question. The minimum-trade floor
        # answers the second, and a position still open counts once because it
        # is one entry, not because its size matters.
        if activity < 1:
            summary["skipped"] = "no_trades"
            summary["minTrades"] = MIN_PUBLISH_TRADES
            results.append(summary)
            _set_conversion_status(
                row["script_id_part"],
                status="no_trades",
                backtest_run_id=run_id,
                diagnostics={
                    "totalTrades": trades,
                    "openPositions": open_positions,
                    "minTrades": MIN_PUBLISH_TRADES,
                },
            )
            _delist_rejected_templates(
                user_id,
                source_id,
                reason="Backtest no longer trades",
            )
            continue

        if trades < MIN_PUBLISH_TRADES:
            # It traded, but not often enough for the result to mean anything.
            # Kept distinct from ``no_trades`` so a later lookback change can
            # requeue exactly this population instead of the whole corpus.
            summary["skipped"] = "too_few_trades"
            summary["minTrades"] = MIN_PUBLISH_TRADES
            results.append(summary)
            _set_conversion_status(
                row["script_id_part"],
                status="too_few_trades",
                backtest_run_id=run_id,
                diagnostics={
                    "totalTrades": trades,
                    "openPositions": open_positions,
                    "minTrades": MIN_PUBLISH_TRADES,
                },
            )
            _delist_rejected_templates(
                user_id,
                source_id,
                reason="Backtest trades too rarely",
            )
            continue

        # A backtest that finished is not automatically a strategy worth
        # shipping, so the thresholds gate the *publish* step. A backtest-only
        # pass still records ``backtested``: rejecting it there would conflate
        # "we measured it" with "we decided not to ship it", and the publish
        # pass re-applies the same gate to the stored numbers later.
        verdict = _publish_verdict(result)
        summary["verdict"] = verdict
        if publish and verdict["rejected"]:
            summary["skipped"] = "below_threshold"
            # A listing may predate the threshold it now fails, so withdraw it
            # rather than leaving a losing strategy advertised.
            delisted = _delist_rejected_templates(
                user_id,
                source_id,
                reason=f"Below publish thresholds ({', '.join(verdict['failed'])})",
            )
            if delisted:
                summary["delisted"] = delisted
            results.append(summary)
            _set_conversion_status(
                row["script_id_part"],
                status="below_threshold",
                backtest_run_id=run_id,
                code_hash=strategy_source_code_hash(code),
                diagnostics={"metrics": verdict["metrics"], "failed": verdict["failed"]},
            )
            continue

        if publish:
            try:
                ok, message, payload = community.publish_script_template_from_strategy(
                    user_id=user_id,
                    strategy_id=0,
                    code=code,
                    name=name,
                    description=str(row.get("description") or ""),
                    pricing_type="free",
                    price=0.0,
                    vip_free=False,
                    code_hidden=False,
                    is_admin=True,
                    existing_indicator_id=0,
                    source_id=source_id,
                    param_schema={},
                )
                summary["published"] = bool(ok)
                if not ok:
                    summary["publish_error"] = message
                else:
                    published += 1
                    indicator_id = 0
                    if isinstance(payload, dict):
                        indicator_id = int(payload.get("indicator_id") or 0)
                    with get_db_connection() as db:
                        cur = db.cursor()
                        try:
                            cur.execute(
                                """
                                UPDATE qd_tv_conversions
                                   SET status = 'published', backtest_run_id = ?,
                                       code_hash = ?, updated_at = NOW()
                                 WHERE script_id_part = ?
                                """,
                                (run_id, strategy_source_code_hash(code), row["script_id_part"]),
                            )
                            db.commit()
                        finally:
                            cur.close()
                    summary["indicator_id"] = indicator_id
            except Exception as exc:
                logger.exception("Publish failed for source %s", source_id)
                summary["publish_error"] = str(exc)
        else:
            _set_conversion_status(
                row["script_id_part"],
                status="backtested",
                backtest_run_id=run_id,
                code_hash=strategy_source_code_hash(code),
            )

        results.append(summary)

    # Each strategy resolves its own window (a secondary subscription can shorten
    # it), so the batch reports the span it actually covered rather than one
    # hard-coded range that was true for nobody.
    spans = [item["range"] for item in results if item.get("range")]
    output = {
        "requested": limit,
        "backtested": len([item for item in results if item.get("run_id")]),
        "published": published,
        "skipped": len([item for item in results if item.get("skipped")]),
        "range": spans[0] if spans else None,
        "results": results,
    }
    logger.info("TradingView backtest/publish batch finished: %s", output)
    return output


def pipeline_status() -> Dict[str, Any]:
    """Aggregate counters for operators and the API route."""
    with get_db_connection() as db:
        cur = db.cursor()
        try:
            cur.execute(
                """
                SELECT status, COUNT(*) AS count
                  FROM qd_tv_conversions
                 GROUP BY status
                """
            )
            conversions = {str(row["status"]): int(row["count"]) for row in (cur.fetchall() or [])}
            cur.execute(
                """
                SELECT COUNT(*) AS total,
                       COUNT(*) FILTER (WHERE source_fetched_at IS NOT NULL) AS with_source,
                       COUNT(*) FILTER (WHERE migratability_score >= 70) AS strong,
                       COUNT(*) FILTER (WHERE migratability_version > 0) AS assessed
                  FROM qd_tv_scripts
                """
            )
            corpus = dict(cur.fetchone() or {})
        finally:
            cur.close()
    return {
        "corpus": corpus,
        "conversions": conversions,
        "assess_version": MIGRATABILITY_VERSION,
        "transpiler_version": TRANSPILER_VERSION,
    }


